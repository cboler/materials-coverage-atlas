import { test, expect } from '@playwright/test';

test.describe('Responsive Shell Smoke Tests', () => {
  test('should load the atlas cleanly without runtime errors or horizontal overflow', async ({
    page,
  }) => {
    const consoleErrors: string[] = [];
    page.on('console', (msg) => {
      // A 404 for the not-yet-generated atlas data is expected (see step 3).
      const missingData = msg.location().url.endsWith('data/atlas.json');
      if (msg.type() === 'error' && !missingData) {
        consoleErrors.push(msg.text());
      }
    });
    page.on('pageerror', (err) => {
      consoleErrors.push(err.message);
    });

    await page.goto('/');

    // 1. Root shell and atlas view
    await expect(page.locator('.brand-title')).toBeVisible();
    await expect(page.locator('#atlas-title')).toBeVisible();
    await expect(page.locator('#overlay-category')).toBeVisible();

    // 2. Primary layout elements are visible
    await expect(page.locator('header[role="banner"]')).toBeVisible();
    await expect(page.locator('main[role="main"]')).toBeVisible();
    await expect(page.locator('footer[role="contentinfo"]')).toBeVisible();

    // 3. Data-dependent checks. public/data/atlas.json is generated by pipeline/build_atlas.py;
    // until it is committed the page shows setup instructions instead, which is also valid.
    const missing = page.locator('#atlas-missing');
    const legend = page.locator('.legend-item').first();
    await expect(missing.or(legend)).toBeVisible();
    if (await legend.isVisible()) {
      await expect(page.locator('#coverage-title')).toBeVisible();
      await expect(page.locator('#pc-title')).toBeVisible();
      await expect(page.locator('#toggle-contours')).toHaveAttribute('aria-pressed', 'true');
      await expect(page.locator('svg.overlay-layer g.contours path').first()).toBeAttached();
      await expect(page.locator('app-parallel-coordinates g.pc-axis')).toHaveCount(9);

      // 4. Overlay switching updates the legend
      await page.locator('#overlay-elastic').click();
      await expect(page.locator('.legend-label').first()).toHaveText('Has elastic data');
    }

    // 5. Prevent accidental horizontal overflow
    const hasHorizontalOverflow = await page.evaluate(() => {
      return document.documentElement.scrollWidth > window.innerWidth;
    });
    expect(hasHorizontalOverflow).toBeFalsy();

    // 6. Unknown deep links fall back to the atlas (SPA routing)
    await page.goto('/no-such-page');
    await expect(page.locator('#atlas-title')).toBeVisible();

    // 7. Zero unhandled console errors or exceptions
    expect(consoleErrors).toEqual([]);
  });
});
